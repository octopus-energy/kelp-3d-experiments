const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const E=require('../js/building/roof-edit.js');
const G=require('../js/building/geometry.js');
const face=(id,coords)=>({id,name:id,active:true,ring:coords.map((p,i)=>({id:id+':'+i,x:p[0],y:p[1],z:p[2]}))});
const base=[face('main',[[0,5,0],[6,5,0],[6,5,8],[0,5,8]])];
const original=JSON.stringify(base);
const changed=E.moveCorner(base,'main',1,{x:7,y:5,z:0},true);
assert.equal(JSON.stringify(base),original,'Edits must not mutate the source');
const edits=E.diff(base,changed);
assert(E.changed(edits));
assert.deepEqual(E.resolve(base,JSON.parse(JSON.stringify(edits))),changed,'JSON replay is exact');
assert.equal(E.changed(E.diff(base,base)),false);
assert.deepEqual(E.resolve(base,null),base,'Reset restores source');
assert.deepEqual(E.validate(changed).errors,[]);
const extension=face('extension',[[6,3,2],[10,3,2],[10,3,6],[6,3,6]]);
assert.deepEqual(E.validate([...base,extension]).errors,[],'Lower extension forms its own closed shell');
const attached=face('attached',[[6,5,2],[10,5,2],[10,5,6],[6,5,6]]);
assert.deepEqual(E.validate([...base,attached]).errors,[],'Shared edge is split at T-junctions');
const split=E.splitFace(base[0],0,2,'second');
assert.deepEqual(E.validate(split).errors,[],'Split face keeps closed topology');
assert.throws(()=>E.splitFace(base[0],0,1,'bad'),/non-adjacent/);
const moved=E.moveCorner(split,'main',0,{x:0,y:6,z:0},true);
assert.equal(moved[1].ring.find(p=>p.id==='main:0').y,6,'Shared ridge corner moves with both faces');
assert.deepEqual(E.validate(moved).errors,[],'Triangular roof faces can change pitch exactly');
const shifted=E.build(moved,{x:50,y:43,z:50});
for(const f of moved)for(const p of f.ring)assert(shifted.clusters.some(c=>Math.hypot(c.x-50-p.x,c.y-43-p.y,c.z-50-p.z)<1e-6),'Measured corners survive the scene-frame conversion');
assert(E.validate([face('crossed',[[0,3,0],[6,3,6],[6,3,0],[0,3,6]])]).errors.some(e=>e.includes('cross')));
assert(E.validate([face('invalid',[[0,3,0],[6,NaN,0],[0,3,6]])]).errors.length);
assert(E.validate([]).errors.length);
assert(E.validate([...base,face('overlap',[[1,3,1],[4,3,1],[4,3,4],[1,3,4]])]).errors.some(e=>e.includes('overlaps')), 'Overlapping volumes must not be accepted just because each is closed');
const state={photoMatches:{front:{landmarks:[{id:'apex_0',px:[.2,.3]}],pose:{pos:[1,2,3]}}}};
E.invalidateMatches(state);
assert.equal(state.roofRevision,1);
assert.equal(state.photoMatches.front.pose,null);
assert.equal(state.photoMatches.front.roofNeedsReview,true);
assert.deepEqual(state.photoMatches.front.landmarks,[],'Old indices cannot be re-solved against changed topology');
assert.equal(state.photoMatches.front.previousLandmarks.length,1,'Old clicks retained for audit');
for(const file of ['data/site-data.js','3broomroad-data/property-bundle.js']) {
 const ctx={window:{}};vm.runInNewContext(fs.readFileSync(path.resolve(__dirname,'..',file),'utf8'),ctx);
 const source=JSON.stringify(ctx.window.SITE_DATA),faces=E.baseFaces(ctx.window.SITE_DATA);
 assert.deepEqual(E.validate(faces).errors,[],file+' canonical roof can be edited without changing it');
 assert.equal(JSON.stringify(ctx.window.SITE_DATA),source);
 const f=faces[0];const more=[...faces,face('extension',[[-20,3,10],[-14,3,10],[-14,3,18],[-20,3,18]])];
 const replay=E.resolve(faces,E.diff(faces,more));assert.deepEqual(E.validate(replay).errors,[]);
 const solid=E.build(replay),slice=G.sliceMesh(solid.verts,solid.tris,1);
 assert.equal(slice.open.length,0);assert(solid.watertight.closed && solid.watertight.oriented);
 console.log('  ok  '+file+' manual-roof replay, closed solid and slices');
}
console.log('all checks passed');
