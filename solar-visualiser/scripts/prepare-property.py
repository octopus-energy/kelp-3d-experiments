#!/usr/bin/env python3
"""Prepare an offline property bundle from a solar export and cached assets.

Usage: python3 scripts/prepare-property.py 3broomroad-data
Requires Pillow for image dimensions. No runtime server or build step is needed.
Cache the export's dsm_url as dsm.asc and image_without_panels_url as aerial.png
in the source directory before running. Source JSON and images are never modified.
"""
import argparse
import base64
import json
import math
import statistics
import struct
from pathlib import Path
from PIL import Image


def inside(x, y, ring):
    hit = False
    for a, b in zip(ring, ring[1:] + ring[:1]):
        if (a[1] > y) != (b[1] > y) and x < (b[0]-a[0]) * (y-a[1]) / (b[1]-a[1]) + a[0]:
            hit = not hit
    return hit


def prepare(folder):
    site = json.loads((folder / 'solarpotential.json').read_text())
    with (folder / 'dsm.asc').open() as src:
        header = dict(src.readline().lower().split() for _ in range(6))
        grid = [float(v) for line in src for v in line.split()]
    meta = dict(ncols=int(header['ncols']), nrows=int(header['nrows']),
                xll=float(header['xllcorner']), yll=float(header['yllcorner']),
                cellsize=float(header['cellsize']), nodata=float(header['nodata_value']))
    assert len(grid) == meta['ncols'] * meta['nrows'], 'Invalid DSM grid size'
    addr = site['property_details']['geocoded_address']
    lat = math.radians(addr['latitude'])
    mlat = 111132.954 - 559.822 * math.cos(2*lat) + 1.175 * math.cos(4*lat)
    mlon = math.pi / 180 * 6378137 * math.cos(lat)
    def local(p):
        return ((p[0]-addr['longitude'])*mlon, (p[1]-addr['latitude'])*mlat)
    cell = meta['cellsize']
    # Solar azimuth is south=0, west=90. Infer only the plane intercept
    # from interior DSM samples; retain the survey's slope and orientation.
    for face in site['roof_faces']:
        ring = face['geometry']['coordinates'][0]
        if all(len(p) >= 3 for p in ring):
            continue
        polygon = [local(p) for p in ring]
        az, slope = math.radians(face['azimuth']), math.radians(face['slope'])
        a, b = math.sin(az)*math.tan(slope), math.cos(az)*math.tan(slope)
        offsets = []
        for row in range(meta['nrows']):
            y = meta['yll'] + (meta['nrows']-row-0.5)*cell - addr['northing']
            for col in range(meta['ncols']):
                x = meta['xll'] + (col+0.5)*cell - addr['easting']
                h = grid[row*meta['ncols']+col]
                if h == meta['nodata'] or not math.isfinite(h):
                    continue
                # Exclude edge pixels that can contain walls / adjacent roofs.
                if all(inside(x+dx, y+dy, polygon) for dx,dy in [(0,0),(.4,0),(-.4,0),(0,.4),(0,-.4)]):
                    offsets.append(h-a*x-b*y)
        if len(offsets) < 3:
            raise ValueError('Insufficient interior DSM samples for roof '+face['id'])
        intercept = statistics.median(offsets)
        face['geometry']['coordinates'][0] = [[p[0],p[1],a*x+b*y+intercept] for p,(x,y) in zip(ring,polygon)]
        face['height_source'] = dict(method='survey-slope-dsm-median', samples=len(offsets),
                                     median_absolute_residual_m=round(statistics.median(abs(v-intercept) for v in offsets),3))
        print(face['id'], face['height_source'])
    site['os_data'] = json.loads((folder / 'osdata.json').read_text()) if (folder / 'osdata.json').exists() else None
    image_data = json.loads((folder / 'image-manifest.json').read_text())
    blobs = {}
    entries = image_data['images'] + ([image_data['floorplan']] if image_data.get('floorplan') else [])
    for entry in entries:
        path = folder / entry['file']
        with Image.open(path) as im:
            entry['imageSize'] = list(im.size)
            mime = Image.MIME[im.format]
        blobs[entry['id']] = 'data:'+mime+';base64,'+base64.b64encode(path.read_bytes()).decode()
    image_data['basePath'] = folder.name + '/'
    aerial = 'data:image/png;base64,'+base64.b64encode((folder/'aerial.png').read_bytes()).decode()
    values = dict(SITE_DATA=site, __DSM_META__=meta,
                  __DSM_B64__=base64.b64encode(struct.pack('<%df'%len(grid), *grid)).decode(),
                  __AERIAL_DATAURL__=aerial, IMAGE_DATA=image_data, __IMAGE_DATAURLS__=blobs)
    output = '// Generated by scripts/prepare-property.py. Do not edit.\n'
    output += ''.join('window.'+k+' = '+json.dumps(v,separators=(',',':'))+';\n' for k,v in values.items())
    (folder / 'property-bundle.js').write_text(output)
    print('Wrote',folder / 'property-bundle.js')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('folder', type=Path)
    prepare(parser.parse_args().folder.resolve())
