#!/usr/bin/env python3
"""Replay the user's rear mono-pitch correction without changing the front fit.
First invocation freezes the previous run as front-fit-baseline.json. Subsequent
runs use that baseline, keeping the same comparisons and front camera geometry.
"""
import copy,json,hashlib
import numpy as np
from scipy.optimize import least_squares
from fit import DATA,OUT,E,dsm_samples
from model import model,world

def main():
 baseline_path=OUT/'front-fit-baseline.json'
 if not baseline_path.exists():baseline_path.write_bytes((OUT/'run.json').read_bytes())
 baseline=json.loads(baseline_path.read_text())
 previous=next(s for s in baseline['stages'] if s['id']==baseline['recommendedStage'])
 original=previous['model']['parameters'];names=['wing_eave','wing_rise','extension_low','extension_rise']
 # Confirmed topology; optimize only the four uncertain rear height parameters.
 # Keep plan/OS location, footprints, front roof, openings and cameras frozen.
 prior=np.array([4.1,1.35,original['extension_low'],original['extension_rise']]);sigma=np.array([.4,.35,.3,.3])
 def residual(x):
  p={**original,**dict(zip(names,x))};pts,y,ids=dsm_samples(p,'both-mono');rear=np.char.startswith(ids,'wing')|(ids=='rear-extension')
  weights=np.where(ids[rear]=='rear-extension',.08,.6)
  return np.r_[(x-prior)/sigma, np.clip((pts[rear,1]-y[rear])/.45,-4,4)*weights]
 result=least_squares(residual,prior,bounds=([3.65,.2,2.35,.05],[6,2.2,3.6,1.3]),loss='soft_l1',max_nfev=150)
 p={**original,**dict(zip(names,map(float,result.x)))};m=model(p,'both-mono')
 world_faces=[]
 for face in m['faces']:
  points=world([[q['x'],q['y'],q['z']] for q in face['ring']],p)
  world_faces.append({**face,'ring':[{**q,'x':float(v[0]),'y':float(v[1]),'z':float(v[2])} for q,v in zip(face['ring'],points)]})
 # Front photo metrics are preserved verbatim: those parameters did not move.
 pts,y,ids=dsm_samples(p,'both-mono');metrics=[]
 for id in dict.fromkeys(ids):
  delta=pts[ids==id,1]-y[ids==id];metrics.append({'faceId':str(id),'samples':len(delta),'medianAbsM':float(np.median(abs(delta))),'rmseM':float(np.sqrt(np.mean(delta**2)))})
 stage={'id':'rear-corrected','label':'Corrected rear · two mono-pitch roofs','model':m,'worldFaces':world_faces,'photos':copy.deepcopy(previous['photos']),'dsm':metrics,'cost':float(result.cost),'evaluations':result.nfev,'fitScope':'Rear height parameters only. Cost is not comparable with the earlier full-model objectives.','frontFitUnchanged':True}
 report=copy.deepcopy(baseline)
 for old in report['stages']:old['label']='Previous · '+old['label']
 report['stages'].append(stage);report['recommendedStage']=stage['id'];report['reviewFocus']='rear';report['evidence']=E
 report['quality'].update(rearRoofAmbiguous=False,rearRoofFormConfirmed=True,rearPitchApproximate=True,frontFitUnchanged=True,extensionDSMConflict=next(d['medianAbsM'] for d in metrics if d['faceId']=='rear-extension')>.5)
 report['quality'].pop('rearHypothesisScoreGap',None)
 report['provenance']['inputs']['reconstruction-observations.json']=hashlib.sha256((DATA/'reconstruction-observations.json').read_bytes()).hexdigest()
 report['provenance']['inputs']['reconstruction/front-fit-baseline.json']=hashlib.sha256(baseline_path.read_bytes()).hexdigest()
 report['provenance']['selection']='User-confirmed mono-pitch topology for both rear volumes; rear-only robust DSM fitting with photo/plan height priors. Front parameters and camera poses are frozen from the previous recommended candidate.'
 report['provenance']['limitations']=[t for t in report['provenance']['limitations'] if not t.startswith(('The two rear roof hypotheses','Rear elevation attribution'))]
 report['provenance']['limitations'].append('Both rear roofs are mono-pitch; the rear camera is not solved and exact rear heights and slopes remain approximate.')
 report['provenance']['rearCorrection']=E['rearRoofCorrection']
 stage['rearFitPriors']={name:{'value':float(value),'sigma':float(spread),'bounds':bounds} for name,value,spread,bounds in zip(names,prior,sigma,[[3.65,6],[.2,2.2],[2.35,3.6],[.05,1.3]])}
 report['parameterDefinitions']['wing_eave']['source']='Mono-pitch low eave; rear-only DSM fit with approximate height prior'
 report['parameterDefinitions']['wing_rise']['source']='User-confirmed mono-pitch form; across-width rise fitted to DSM'
 report['parameterDefinitions']['extension_rise']['source']='User-confirmed mono-pitch form; approximate rise and slope direction'
 for filename,value in [('run.json',report),('candidate.json',m)]: (OUT/filename).write_text(json.dumps(value,indent=2,allow_nan=False)+'\n')
 (OUT/'bundle.js').write_text('// Generated by reconstruction/revise_rear.py. Do not hand-edit.\nwindow.BROOM_RECONSTRUCTION = '+json.dumps(report,separators=(',',':'),allow_nan=False)+';\n')
 print('Rear corrected:',{k:round(p[k],3) for k in names})
 print('DSM medians:',[(d['faceId'],round(d['medianAbsM'],3)) for d in metrics])
 print('Front geometry and camera poses unchanged.')
if __name__=='__main__':main()
