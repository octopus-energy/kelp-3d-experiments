#!/usr/bin/env python3
"""Fit provisional rear cameras with frozen geometry; retain withheld roof checks."""
import copy,json,math,hashlib
import numpy as np
from scipy.optimize import least_squares
from fit import DATA,OUT
from model import project

def landmarks(m):
 p=m['parameters'];w=p['wing_width'];z=p['wing_end'];e=p['extension_end']
 return {'wing-low':[w,p['wing_eave'],z],'wing-high':[0,p['wing_eave']+p['wing_rise'],z],
         'extension-low':[w,p['extension_low'],e],
         'door-left':m['landmarks']['rear-door_br'],'door-right':m['landmarks']['rear-door_bl']}

def align(m,photo):
 lm=landmarks(m);p=m['parameters'];pose=[o for o in photo['points'] if o['use']=='pose'];xyz=[lm[o['landmark']] for o in pose];target=np.array([o['px'] for o in pose])*[1024,683]
 low=np.array([-20,-1,p['extension_end']+3,math.pi-1.2,-.4,-.12,25,-180]);high=np.array([25,4,p['extension_end']+60,math.pi+1.2,.5,.12,100,180])
 def residual(c):
  r=((project(xyz,c)-target)/np.array([o['sigmaPx'] for o in pose])[:,None]).ravel().tolist()
  for edge in photo['verticals']:
   a=np.array(lm[edge['landmark']]);v=np.diff(project([a,a-[0,2,0]],c),axis=0)[0];v/=np.linalg.norm(v)
   q=np.array(edge['end'],dtype=float)-edge['start'];q/=np.linalg.norm(q)
   r.append((v[0]*q[1]-v[1]*q[0])/.006)
  r.extend([(c[1]-1.3)/1.2,c[4]/.15,c[5]/.04,c[7]/100])
  return np.array(r)
 candidates=[]
 for distance in [8,16,30]:
  for x in [0,5,10]:
   c=[x,1.3,p['extension_end']+distance,math.pi+math.atan2(x-p['wing_width']/2,distance),0,0,55,0]
   result=least_squares(residual,c,bounds=(low,high),loss='soft_l1',max_nfev=400)
   candidates.append(result)
 result=min(candidates,key=lambda r:r.cost);c=result.x;records=[]
 for o in photo['points']:
  uv=project([lm[o['landmark']]],c)[0];delta=uv-np.array(o['px'])*[1024,683]
  records.append({**o,'projectedPx':uv.tolist(),'errorPx':float(np.linalg.norm(delta))})
 a=project([lm['extension-low'],[.75,p['extension_low']+p['extension_rise']*(1-.75/p['wing_width']),p['extension_end']]],c);v=a[1]-a[0]
 checks=[]
 for edge in photo['checkEdges']:
  q=np.array(edge['pixels']);dist=np.abs(v[0]*(q-a[0])[:,1]-v[1]*(q-a[0])[:,0])/np.linalg.norm(v)
  checks.append({**edge,'meanDistancePx':float(np.mean(dist)),'projectedSegmentPx':a.tolist()})
 bound_hits=[name for i,name in enumerate(['x','height','distance','yaw','pitch','roll','fov','imageShift']) if min(c[i]-low[i],high[i]-c[i])<.01]
 check_rmse=float(np.sqrt(np.mean([o['errorPx']**2 for o in records if o['use']=='check'])))
 return {'imageId':photo['imageId'],'camera':c.tolist(),'status':'failed-check' if bound_hits or check_rmse>10 else 'needs-review','boundHits':bound_hits,'checkThresholdPx':10,'poseRmsePx':float(np.sqrt(np.mean([o['errorPx']**2 for o in records if o['use']=='pose']))),'checkRmsePx':check_rmse,'points':records,'checkEdges':checks,'landmarks':lm,'note':'Camera-only alignment; geometry frozen. Four approximate pose points and vertical directions leave focal-length/distance ambiguity. Cyan roof checks were excluded from camera fitting. The 10 px threshold is a prototype diagnostic, not survey accuracy. No rear accuracy certification.'}

def main():
 report=json.loads((OUT/'run.json').read_text());source=DATA/'rear-observations.json';e=json.loads(source.read_text());stage=next(s for s in report['stages'] if s['id']==report['recommendedStage'])
 reviews=[align(stage['model'],ph) for ph in e['photos']]
 report['rearReview']={'stageId':stage['id'],'status':'failed-check' if any(ph['status']=='failed-check' for ph in reviews) else 'needs-review','annotationSource':'rear-observations.json','photos':reviews,'geometryChanged':False}
 report['provenance']['inputs']['rear-observations.json']=hashlib.sha256(source.read_bytes()).hexdigest()
 report['provenance']['limitations']=[t.replace('the rear camera is not solved','the rear cameras are provisional') for t in report['provenance']['limitations']]
 (OUT/'run.json').write_text(json.dumps(report,indent=2,allow_nan=False)+'\n');(OUT/'bundle.js').write_text('// Generated by reconstruction/run.py. Do not hand-edit.\nwindow.BROOM_RECONSTRUCTION = '+json.dumps(report,separators=(',',':'),allow_nan=False)+';\n')
 for ph in reviews:print(ph['imageId'], 'pose',round(ph['poseRmsePx'],1),'withheld corner',round(ph['checkRmsePx'],1),'edge',round(ph['checkEdges'][0]['meanDistancePx'],1),'camera',np.round(ph['camera'],2))
if __name__=='__main__':main()
