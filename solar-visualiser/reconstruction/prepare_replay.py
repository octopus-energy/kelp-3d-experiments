#!/usr/bin/env python3
"""Package the curated Broom replay and exact, hash-checked prediction previews.
No fitting or inference; stdlib only. Run after reconstruction/run.py.
"""
import base64
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
APP = HERE.parent
DATA = APP / '3broomroad-data'
PACKAGE = DATA / 'broom-road-run-03-evidence-217598ab'

def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def build():
    story = json.loads((HERE / 'replay-story.json').read_text())
    report = json.loads((DATA / 'reconstruction/run.json').read_text())
    manifest = json.loads((PACKAGE / 'manifest.json').read_text())
    assert story['propertyId'] == report['propertyId'] == manifest['settings']['property_id']
    stage_ids = {s['id'] for s in report['stages']}
    assets = {}
    for image_id in sorted({e['imageId'] for e in story['events'] if 'imageId' in e}):
        im = next(i for i in manifest['images'] if Path(i['source']).stem == image_id)
        source = DATA / 'photos' / im['source']
        assert sha(source) == im['source_sha256'], f'Source changed: {source}'
        assert im['transform']['crop'] is None and im['input_size'] == [1024, 683], 'Replay projections require this recorded image frame'
        assets[image_id] = {}
        for modality in ('normals', 'depth'):
            output = im['outputs'][modality]
            preview, array = PACKAGE / output['png'], PACKAGE / output['npy']
            assert sha(preview) == output['png_sha256'] and sha(array) == output['npy_sha256'], f'Prediction changed: {image_id}/{modality}'
            assets[image_id][modality] = {
                'id': f'replay-{image_id}-{modality}',
                'dataUrl': 'data:image/png;base64,' + base64.b64encode(preview.read_bytes()).decode(),
                'source': str(preview.relative_to(APP)), 'array': str(array.relative_to(APP)),
                'sha256': output['png_sha256'], 'arraySha256': output['npy_sha256'],
                'sourceSha256': im['source_sha256'], 'encoding': output['encoding'],
                'size': im['input_size'],
            }
    for event in story['events']:
        assert event['stageId'] in stage_ids
        assert not event.get('previousStageId') or event['previousStageId'] in stage_ids
        if event['evidence'] in ('normals', 'depth'):
            assert event['evidence'] in assets[event['imageId']]
    assert story['events'][-1]['stageId'] == report['recommendedStage'], 'Latest geometry must be reachable in replay'
    story['geometryEvidence'] = report['stages'][-1].get('openingReview')
    story['assets'] = assets
    story['runSha256'] = sha(DATA / 'reconstruction/run.json')
    story['manifestSha256'] = sha(PACKAGE / 'manifest.json')
    story['sourceFiles'] = {str(p.relative_to(APP)): sha(p) for p in [HERE / 'replay-story.json', DATA / 'reconstruction/run.json', PACKAGE / 'manifest.json']}
    return story

def main():
    result = build()
    target = DATA / 'reconstruction/replay-bundle.js'
    target.write_text('// Generated by reconstruction/prepare_replay.py; do not edit.\nwindow.BROOM_REPLAY = ' + json.dumps(result, separators=(',', ':'), allow_nan=False) + ';\n')
    print(f'Replay: {len(result["events"])} steps, {len(result["assets"])} photos; {target.stat().st_size / 1e6:.1f} MB offline bundle')

if __name__ == '__main__':
    main()
