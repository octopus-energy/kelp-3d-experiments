#!/usr/bin/env python3
"""Replay the reviewed Broom Road adapter and generate its evidence/survey pack.
Other datasets: use prepare_evidence.py for intake, then author a reviewed adapter.
"""
import hashlib,json,subprocess,sys
import numpy,scipy
from pathlib import Path
HERE=Path(__file__).resolve().parent

def main():
 for script in ['revise_rear.py','align_rear.py','trial_rear.py','refine_exterior.py']:
  subprocess.run([sys.executable,str(HERE/script)],check=True)
 subprocess.run([sys.executable,str(HERE/'prepare_evidence.py'),str(HERE.parent/'3broomroad-data')],check=True)
 data=HERE.parent/'3broomroad-data'/'reconstruction';report=json.loads((data/'run.json').read_text());workflow=json.loads((data/'workflow.json').read_text())
 for source in workflow['sources']:
  if source['sha256']:report['provenance']['inputs'][source['path']]=source['sha256']
 report['rearGeometryTrial']=json.loads((data/'rear-trial.json').read_text());
 report['workflowRevision']=workflow['revision'];report['quality']['rearPhotoValidation']=report['rearReview']['status']
 report['provenance']['replayCommand']='python solar-visualiser/reconstruction/run.py'
 report['provenance']['runtime']={'python':sys.version.split()[0],'numpy':numpy.__version__,'scipy':scipy.__version__}
 report['provenance']['codeHashes']={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(HERE.glob('*.py'))}
 (data/'run.json').write_text(json.dumps(report,indent=2,allow_nan=False)+'\n');(data/'bundle.js').write_text('// Generated by reconstruction/run.py. Do not hand-edit.\nwindow.BROOM_RECONSTRUCTION = '+json.dumps(report,separators=(',',':'),allow_nan=False)+';\n')
if __name__=='__main__':main()
